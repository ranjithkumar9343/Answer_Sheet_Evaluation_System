# setup the clients
client = Groq(api_key=GROQ_API_KEY)
genai.configure(api_key=GOOGLE_API_KEY)
model = genai.GenerativeModel('models/gemini-1.5-pro-001')


# --- HELPER FUNCTIONS ---

def extract_text_from_image(image_path):
    # grab the handwritten text from the uploaded answer script using gemini
    img_ = Image(image_path)
    prompt = 'analyze and extract all text information from image, it is usually an answer script'
    result = model.generate_content([img_, prompt])
    return result.text

def evaluate_answer(extracted_text):
    # pass the extracted text to llama3 to grade it on 3 criteria
    chat_completion = client.chat.completions.create(
        messages=[
            {
                "role": "user",
                "content": 'In the following text, do three tasks: check whether its keywords are relevant and give it a score from 1-100, check whether its semantically similar in meaning to a good answer by a good student, also give it a score from 1 to 100, and finally rate its grammar from 1-100. Respond only with the numerical scores (keyword, semantic, grammar in order) separated by spaces, no other words. \n\n' + extracted_text,
            }
        ],
        model="llama3-70b-8192",
    )

    text12 = chat_completion.choices[0].message.content
    score = text12.split()

    # weights for the final grade calculation
    grammar_weight = 0.2
    keyword_weight = 0.2
    semantic_weight = 0.6
    
    # wrapping in a try/except because sometimes the LLM ignores instructions and spits out words instead of just numbers
    try:
        keywordscore = int(score[0])
        Semanticscore = int(score[1])
        Grammarscore = int(score[2])
    except (IndexError, ValueError):
        # safe fallback if the LLM output is messed up
        return 0, 0, 0, 0 

    weighted_grade = (Grammarscore * grammar_weight + keywordscore * keyword_weight + Semanticscore * semantic_weight)
    
    return keywordscore, Semanticscore, Grammarscore, weighted_grade

def give_feedback(extracted_text, keywordscore, Semanticscore, Grammarscore, weighted_grade):
    # generate some helpful feedback for the student based on what they wrote
    chat_completion = client.chat.completions.create(
        messages=[
            {
                "role": "user",
                "content": 'For the following text, provide concise feedback on how the student can improve their answer: \n\n' + extracted_text,
            }
        ],
        model="llama3-70b-8192",
    )

    text13 = chat_completion.choices[0].message.content
    return text13

def integration_function(image_path):
    # master function to run the whole pipeline sequentially for the UI
    extracted_text = extract_text_from_image(image_path)
    
    Final_grade = evaluate_answer(extracted_text)
    keywordscore, Semanticscore, Grammarscore, weighted_grade = Final_grade
    
    Feedback_Text = give_feedback(extracted_text, keywordscore, Semanticscore, Grammarscore, weighted_grade)
    
    return extracted_text, keywordscore, Semanticscore, Grammarscore, weighted_grade, Feedback_Text


